"""Write web/static/mpl_data.js: matplotlib colormap tables, CSS4 colour names and the ColorManager palettes.

The JS engine needs the exact colour lookup tables matplotlib uses for the colormaps the generators name (viridis,
gray, hot, cool, rainbow, hsv) and the named colours they use ('gray', 'darkgray', 'gold', ...).
tests/test_web.py checks the file is current.

Run: python scripts/make_mpl_data.py [--check]
"""
import json
import sys
from pathlib import Path

import matplotlib
import numpy as np
from matplotlib.colors import CSS4_COLORS

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from config import ColorManager  # noqa: E402

OUT = ROOT / "web" / "static" / "mpl_data.js"
CMAPS = ["viridis", "gray", "hot", "cool", "rainbow", "hsv"]


def tables():
    cm = {}
    for name in CMAPS:
        lut = matplotlib.colormaps[name](np.arange(256))[:, :3]
        cm[name] = [round(float(v), 6) for v in lut.ravel()]
    return cm


def text():
    lines = ["// Generated by scripts/make_mpl_data.py from matplotlib " + matplotlib.__version__ + " and config.py: do not edit.",
             "// CMAPS: 256-entry RGB lookup tables (flat r,g,b floats); CSS4: matplotlib named colours; PALETTES: ColorManager.PALETTES.",
             "export const CMAPS = {"]
    for name, vals in tables().items():
        lines.append(f"  {name}: {json.dumps(vals, separators=(',', ':'))},")
    lines.append("};")
    lines.append("export const CSS4 = " + json.dumps(CSS4_COLORS, separators=(",", ":")) + ";")
    lines.append("export const PALETTES = " + json.dumps(ColorManager.PALETTES, separators=(",", ":")) + ";")
    return "\n".join(lines) + "\n"


def current():
    return OUT.exists() and OUT.read_text() == text()


if __name__ == "__main__":
    if "--check" in sys.argv:
        print("current" if current() else "STALE")
        sys.exit(0 if current() else 1)
    OUT.write_text(text())
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")
